// 根拠：事業所のノウビー実記録の集計（2026-07-01〜10-01 約2,000件＋2026-09-09〜10-08 655件の詳細集計）。
// 実記録の文章はここに入れていない。見本はすべて架空。
//  在宅（72%）：4段落「09:38作業開始の連絡頂きました。」→開始時の話→「11:06作業終了の連絡頂きました。」→終了時の話。
//              記録 中央値343字（多くは300〜370）、考察 中央値177字（155〜190）。考察1行目は「チラシ折り5setされました。」。
//  通所：「09:40に来所されました。」で始め1〜2段落、「11:45に退所されました。」。記録249字（200〜320）、考察156字（130〜190）。考察に作業量の行は無い。
//  施設外：「施設外就労先へ到着後、」などで始め1段落。記録221字（180〜265）、考察172字（150〜185）。考察に作業量の行は無い。
//  記録の語尾：「〜とのことでした」「〜されていました」「〜と報告がありました」「〜と話されました」「〜をお伝えしました」。
//  考察：今日の様子（「開始時から〜」）→見立て（「〜ができています」「〜と考えられます」）→「今後も〜支援していきます。」（約9割）。
export type UseMode='在宅'|'通所'|'施設外'|'未指定';
type Range=readonly [number,number];

// ノウビー実測の中心的な範囲（空白・改行を除く字数）。画面の目安表示に使う。
export const styleTargets:Record<UseMode,{record:Range;consideration:Range}>={
 在宅:{record:[300,370],consideration:[155,190]},
 通所:{record:[200,320],consideration:[130,190]},
 施設外:{record:[180,265],consideration:[150,185]},
 未指定:{record:[170,250],consideration:[140,180]},
};

const headerOnly=/^\s*\d{1,2}[:：]\d{2}\s*(?:作業(?:開始|終了)の連絡.*|来所.*|退所.*|開始|終了)\s*$/;
const workLine=/^\s*作業[:：]/;
// 利用の形が未指定でも、メモに書かれた語（連絡・来所・施設外）から書式を選ぶ。推測で事実は足さない。
// メモに手がかりが無い時だけ、最近の記録の書式（recent：最近の記録の本文）を使う。
export function resolveMode(mode:string|undefined,memo:string,recent=''):UseMode{
 if(mode==='在宅'||mode==='通所'||mode==='施設外')return mode;
 for(const text of [memo,recent]){
  if(/施設外/.test(text))return '施設外';
  if(/作業(?:開始|終了)の(?:ご)?連絡|電話|在宅/.test(text))return '在宅';
  if(/来所|退所|送迎|通所/.test(text))return '通所';
 }
 return '未指定';
}
// 時刻の見出しと作業名・量の行を除いた、今日の出来事の数
export function memoFacts(memo:string){
 return memo.split('\n').filter(l=>l.trim()&&!headerOnly.test(l)&&!workLine.test(l))
  .flatMap(l=>l.split(/[。]/)).map(s=>s.trim()).filter(s=>s.length>=2).length;
}
export const isWorkOnly=(memo:string)=>memoFacts(memo)===0;

// 今日のメモの事実の量から、文字数の目安を決める（事実が少ない日に水増しさせない）。
// target の下限は「短すぎるので書き直しを頼む」基準、上限はノウビー実測の上限。
export function lengthPlan(mode:UseMode,memo:string){
 const f=memoFacts(memo),t=styleTargets[mode];
 const clamp=(v:number,[lo,hi]:Range)=>Math.max(lo,Math.min(hi,Math.round(v/10)*10));
 const head=mode==='在宅'?40:mode==='通所'?30:0;
 const record=isWorkOnly(memo)?40:clamp(head+f*45,[60,t.record[1]]);
 const consideration=isWorkOnly(memo)?60:clamp((mode==='在宅'?20:0)+Math.min(f,4)*42,[80,t.consideration[1]]);
 const retry=f>=2;
 return {
  hint:{record,consideration},
  target:{record:[retry?Math.round(record*0.75):0,t.record[1]] as Range,consideration:[retry?Math.round(consideration*0.75):0,t.consideration[1]] as Range},
 };
}

